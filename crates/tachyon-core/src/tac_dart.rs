    fn read(source: &str, class: &str, models: &[String]) -> Result<Self, String> {
        let mask = crate::lexical::code_mask("dart", source);
        if let Some(error) = mask.error {
            return Err(error.to_owned());
        }
        let code = String::from_utf8(masked_code(source, &mask.code))
            .map_err(|_| "the service source is not UTF-8".to_owned())?;
        if top_level_main(&code) {
            return Err(
                "a service may not declare main(); Tachyon writes the program's entry point"
                    .to_owned(),
            );
        }
        let classes = classes(&code, source, models);
        let service = classes
            .iter()
            .find(|candidate| candidate.name == class)
            .cloned()
            .ok_or_else(|| format!("the source declares no class {class}"))?;
        let publishes = source.contains(Self::PUBLISHER);
        Ok(Self {
            service,
            classes,
            publishes,
            stored: Vec::new(),
        })
    }

    fn check_plan(&self, plan: Option<&serde_json::Value>) -> Result<(), String> {
        let Some(plan) = plan else {
            return Ok(());
        };
        let mut named = Vec::new();
        for key in ["post_construct", "pre_destroy"] {
            if let Some(method) = plan[key].as_str() {
                named.push(method);
            }
        }
        if let Some(listeners) = plan["listeners"].as_array() {
            for listener in listeners {
                if let Some(method) = listener["method"].as_str() {
                    named.push(method);
                }
            }
        }
        for method in named {
            if !self.has_method(method) {
                return Err(format!(
                    "lifecycle and listener method '{method}' must be public, with JSON parameters and result"
                ));
            }
        }
        Ok(())
    }

    fn held_streams(
        &self,
        clients: &[(String, EventStream)],
    ) -> Result<Vec<serde_json::Value>, String> {
        let held: Vec<serde_json::Value> = clients
            .iter()
            .filter(|(client, _)| self.holds(client))
            .map(|(client, stream)| Self::held_stream(client, stream))
            .collect();
        if held.len() > Self::MOST_STREAMS {
            return Err(
                "a Dart service holds at most 16 @StreamRequest and @SocketRequest methods through its clients"
                    .to_owned(),
            );
        }
        Ok(held)
    }

    fn holds(&self, client: &str) -> bool {
        self.service
            .declared
            .iter()
            .filter_map(|(_, type_name)| type_name.as_deref())
            .any(|type_name| type_name.trim_end_matches('?') == client)
    }

    fn held_stream(client: &str, stream: &EventStream) -> serde_json::Value {
        serde_json::json!({
            "method": "__tachyonStream",
            "path": stream.path,
            "event": stream.event,
            "socket": stream.socket,
            "models": stream.models,
            "sender": format!("__tachyonSend:{client}"),
        })
    }

    fn with_sockets(mut self, clients: &[(String, EventStream)]) -> Self {
        for class in &mut self.classes {
            class.socket = clients
                .iter()
                .any(|(client, stream)| [client == &class.name, stream.socket] == [true, true]);
        }
        self
    }

    fn has_method(&self, name: &str) -> bool {
        self.service
            .methods
            .iter()
            .any(|candidate| candidate.name == name)
    }

    fn injections(
        &self,
        dart: &BTreeSet<&str>,
        instances: &BTreeSet<String>,
        class: &str,
    ) -> Result<Vec<Injection>, String> {
        let mut result = Vec::new();
        for (field, type_name) in &self.service.declared {
            let Some(type_name) = type_name.as_deref() else {
                continue;
            };
            let type_name = type_name.trim_end_matches('?');
            if type_name == "TacService" {
                result.push(Self::tac_service_injection(field, instances)?);
                continue;
            }
            if type_name == class || !dart.contains(type_name) || self.declares_class(type_name) {
                continue;
            }
            result.push(Self::dart_service_injection(field, type_name)?);
        }
        Ok(result)
    }

    fn declares_class(&self, name: &str) -> bool {
        self.classes.iter().any(|declared| declared.name == name)
    }

    fn tac_service_injection(
        field: &str,
        instances: &BTreeSet<String>,
    ) -> Result<Injection, String> {
        if !instances.contains(field) {
            return Err(format!(
                "TacService field '{field}' is filled by the service addressed as '{field}', and there is none"
            ));
        }
        Ok(Injection {
            field: field.to_owned(),
            dart: None,
        })
    }

    fn dart_service_injection(field: &str, type_name: &str) -> Result<Injection, String> {
        let expected = crate::template::instance_name(type_name);
        if field != expected {
            return Err(format!(
                "field '{field}' holds the {type_name} service, which is injected by its instance name; name it '{expected}'"
            ));
        }
        Ok(Injection {
            field: field.to_owned(),
            dart: Some(type_name.to_owned()),
        })
    }

    fn library(
        &self,
        source: &str,
        class: &str,
        injections: &[Injection],
        models: &DartModels,
    ) -> Result<String, String> {
        let mut program = String::from(
            "import 'dart:js_interop';\nimport 'dart:js_interop_unsafe';\nimport 'tachyon.dart';\n",
        );
        let (imports, inject) = injection_code(injections);
        program.push_str(&imports);
        program.push_str(&models.imports);
        program.push_str(source);
        program.push('\n');
        program.push_str(&models.code);
        let mut constructors = String::new();
        let mut visiting = Vec::new();
        construct(&self.classes, class, &mut visiting, &mut constructors)?;
        let (get, set) = self.field_cases(&models.names);
        let call = self.call_cases(&models.names);
        let mut cases = switch_section("get", &get);
        cases.push_str(&switch_section("set", &set));
        cases.push_str(&switch_section("call", &call));
        cases.push_str(&switch_section("inject", &inject));
        program.push_str(&bridge_class_source(
            class,
            &constructors,
            &cases,
            source.contains("abstract final class BehaviorBrowserHttp {"),
        ));
        Ok(program)
    }

    fn field_cases(&self, models: &[String]) -> (String, String) {
        let mut get = String::new();
        let mut set = String::new();
        for field in &self.service.fields {
            let _ = writeln!(
                get,
                "          case r'{0}': return __yon_json(service.{0}).jsify();",
                field.name
            );
            if field.writable {
                let _ = writeln!(
                    set,
                    "          case r'{0}': service.{0} = {1}; return null;",
                    field.name,
                    DartModelShape::field_value(field.type_name.as_deref(), models)
                );
            }
        }
        (get, set)
    }

    fn call_cases(&self, models: &[String]) -> String {
        let mut call = String::new();
        for method in &self.service.methods {
            let (arguments, least, most) = method.arguments(models);
            let invocation = format!("service.{}({arguments})", method.name);
            let body = if method.returns.as_deref() == Some("void") {
                format!("{invocation}; return null;")
            } else {
                format!("return __TacDartBridge.result({invocation});")
            };
            let _ = writeln!(
                call,
                "          case r'{}': __TacDartBridge.arity(values, {least}, {most}); {body}",
                method.name,
            );
        }
        call
    }

    fn member_lists(&self, injections: &[Injection]) -> [String; 4] {
        let mut fields = Vec::new();
        let mut readonly = Vec::new();
        for field in &self.service.fields {
            fields.push(&field.name);
            if !field.writable {
                readonly.push(&field.name);
            }
        }
        let mut methods = Vec::new();
        for method in &self.service.methods {
            methods.push(&method.name);
        }
        let mut injected = Vec::new();
        for injection in injections {
            injected.push((&injection.field, injection.dart.is_some()));
        }
        [
            json_text(&fields),
            json_text(&readonly),
            json_text(&methods),
            json_text(&injected),
        ]
    }

    fn with_stored(mut self, source: &str) -> Result<Self, String> {
        let stored = crate::behavior::StoredState::fields(
            std::path::Path::new("client/services/service.dart"),
            source,
        )
        .map_err(|failure| failure.to_string())?;
        for field in &self.service.fields {
            if stored.contains_key(&field.name) && !field.writable {
                return Err(format!(
                    "the stored field '{}' is restored by assignment, so it cannot be final or a getter",
                    field.name
                ));
            }
        }
        self.stored = stored.into_keys().collect();
        Ok(self)
    }

    fn module_plan(
        &self,
        class: &str,
        plan: Option<&serde_json::Value>,
        mut held: Vec<serde_json::Value>,
    ) -> serde_json::Value {
        let mut plan = plan
            .cloned()
            .unwrap_or_else(|| serde_json::json!({ "name": class }));
        held.extend(plan["streams"].as_array().cloned().unwrap_or_default());
        plan["streams"] = serde_json::Value::Array(held);
        if self.publishes {
            plan["resources"] = serde_json::json!([{ "field": Self::PUBLISHER_RESOURCE, "name": "applicationEventPublisher" }]);
        }
        serde_json::json!({ "types": [plan] })
    }

