    #[tokio::test]
    async fn a_dart_service_uses_the_builtin_cache_and_store() {
        if !dart_and_node_available() {
            eprintln!("skipping: dart or node is unavailable");
            return;
        }
        let root = tempfile::tempdir().expect("project");
        write_file(
            root.path(),
            "client/setups/NotesSetup.dart",
            "@Setup()\nclass NotesSetup {\n  static BehaviorAdapters configure(BehaviorExecution execution) {\n    return BehaviorAdapters();\n  }\n}\n",
        );
        write_file(
            root.path(),
            "client/entities/NoteEntity.dart",
            "@Entity({\"adapter\":\"indexeddb\"})\n@Table(\"notes\")\nclass NoteEntity {\n  @Id\n  String id = '';\n  String text = '';\n}\n",
        );
        write_file(
            root.path(),
            "client/services/NotesService.dart",
            "@Service()\n@CacheSettings({\"name\":\"notes\",\"ttlMs\":60000,\"maxBytes\":4096,\"maxEntries\":8})\nclass NotesService {\n  \
             late BehaviorContext behaviors;\n  int reads = 0;\n\n  \
             @OnStart\n  void open() {\n    behaviors = Behaviors.create(NotesSetup, partition: 'notes', signal: BehaviorSignal());\n  }\n\n  \
             @Cached\n  Future<Object?> find(String key) async {\n    reads += 1;\n    return {'key': key, 'reads': reads};\n  }\n\n  \
             @ClearCache({\"method\":\"find\"})\n  Future<Object?> forget(String key) async {\n    return {'key': key};\n  }\n\n  \
             Future<Object?> save(String id, String text) {\n    return behaviors.repository(NoteEntity).save({'id': id, 'text': text});\n  }\n\n  \
             @AllOrNothing({\"adapter\":\"indexeddb\"})\n  Future<Object?> refuse(String id) async {\n    \
             await behaviors.repository(NoteEntity).save({'id': id, 'text': 'draft'});\n    throw BehaviorError('REFUSED');\n  }\n\n  \
             Future<Object?> list() {\n    return behaviors.repository(NoteEntity).find();\n  }\n}\n",
        );
        publish(
            root.path(),
            &[("NotesService", "client/services/NotesService.dart")],
            &["notes"],
        )
        .await;
        std::fs::write(
            root.path().join("tac-storage.js"),
            include_str!("template/tac-storage.js"),
        )
        .expect("storage runtime");
        let report = node(
            root.path(),
            "import { readFile } from 'node:fs/promises'\n\
             console.info = () => {}\n\
             globalThis.indexedDB = { databases: async () => [], open: () => ({}) }\n\
             ;(0, eval)(await readFile('./tac-storage.js', 'utf8'))\n\
             const { default: NotesService, __tachyon_event_plan__: plan } = await import('./NotesService.js')\n\
             const notes = new NotesService({})\n\
             notes[plan.types[0].post_construct]()\n\
             const first = await notes.find('a')\n\
             const second = await notes.find('a')\n\
             await notes.forget('a')\n\
             const third = await notes.find('a')\n\
             await notes.save('n1', 'hello')\n\
             const refused = await notes.refuse('n2').then(() => 'saved', () => 'refused')\n\
             console.log(JSON.stringify({ first, second, third, refused, listed: await notes.list() }))\n",
        );
        assert_eq!(report["first"], serde_json::json!({"key": "a", "reads": 1}));
        assert_eq!(report["second"], report["first"]);
        assert_eq!(report["third"], serde_json::json!({"key": "a", "reads": 2}));
        assert_eq!(report["refused"], "refused");
        assert_eq!(
            report["listed"],
            serde_json::json!([{"id": "n1", "text": "hello"}])
        );
    }

