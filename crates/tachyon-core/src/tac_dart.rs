struct DartCompiler;

impl DartCompiler {
    const ALL_SERVICES: &str = "client/services/*Service.dart";
}

pub(crate) async fn build_all(
    snapshot_root: &Path,
    services: &[(&str, &Path)],
    instances: &BTreeSet<String>,
    profile: crate::BuildProfile,
) -> Result<Vec<(String, Vec<u8>)>, Failure> {
    let mut dart = BTreeSet::new();
    for (class, _) in services {
        dart.insert(*class);
    }
    let shared = format!(
        "{}{}",
        Bridge::SHARED_LIBRARY,
        crate::route_types::WebEventSources::dart()
    );
    let mut libraries = vec![("tachyon.dart".to_owned(), shared)];
    let mut published = Vec::new();
    let mut main = String::from(
        "// Generated by Tachyon (ADR 0033): every Dart browser service, registered once.\nimport 'tachyon.dart' as tachyon;\n",
    );
    let mut register = String::new();
    for (index, (class, path)) in services.iter().enumerate() {
        let (library, module) = build_service(snapshot_root, class, path, &dart, instances)?;
        let uses_storage = library.contains("final class BehaviorStorage {");
        let uses_http = library.contains("abstract final class BehaviorBrowserHttp {");
        libraries.push((format!("{class}.dart"), library));
        let _ = writeln!(main, "import '{class}.dart' as s{index};");
        if uses_storage {
            let _ = writeln!(
                register,
                "  s{index}.BehaviorStorage.host = tachyon.tachyonStorageHost;"
            );
        }
        if uses_http {
            let _ = writeln!(
                register,
                "  s{index}.BehaviorBrowserHttp.host = (request, signal) => tachyon.tachyonHttpHost(request, signal.watch);"
            );
        }
        let _ = writeln!(register, "  s{index}.tachyonRegister{class}();");
        published.push((format!("{class}.js"), module.into_bytes()));
    }
    let _ = write!(main, "\nvoid main() {{\n{register}}}\n");
    libraries.push(("main.dart".to_owned(), main));
    libraries.extend(model_libraries(snapshot_root)?);
    let program = WasmProgram::compile(&libraries, DartCompiler::ALL_SERVICES, profile).await?;
    published.extend(program.published());
    Ok(published)
}

pub(crate) fn compiler_note(profile: crate::BuildProfile) -> Option<String> {
    WasmProgram::note(profile)
}

fn model_libraries(snapshot_root: &Path) -> Result<Vec<(String, String)>, Failure> {
    let models = crate::model_sources::ModelSources::read(snapshot_root, "client", "dart")?;
    let mut libraries = Vec::new();
    for (relative, source) in models.separate_files() {
        let name = relative.to_string_lossy().replace('\\', "/");
        libraries.push((name, source));
    }
    Ok(libraries)
}

fn build_service(
    snapshot_root: &Path,
    class: &str,
    path: &Path,
    dart: &BTreeSet<&str>,
    instances: &BTreeSet<String>,
) -> Result<(String, String), Failure> {
    let relative = path.strip_prefix(snapshot_root).unwrap_or(path);
    let portable = relative.to_string_lossy().replace('\\', "/");
    let source = std::fs::read_to_string(path)
        .map_err(|error| failure(&portable, format!("cannot read the service: {error}")))?;
    let unit = prepare(snapshot_root, relative, &source)?;
    let models = DartModels::read(snapshot_root).map_err(|message| failure(&portable, message))?;
    let bridge = Bridge::read(&unit.source, class, &models.names)
        .and_then(|bridge| bridge.with_stored(&source))
        .map_err(|message| failure(&portable, message))?;
    bridge
        .check_plan(unit.plan.as_ref())
        .map_err(|message| failure(&portable, message))?;
    let held = bridge
        .held_streams(&unit.clients)
        .map_err(|message| failure(&portable, message))?;
    let bridge = bridge.with_sockets(&unit.clients);
    let injections = bridge
        .injections(dart, instances, class)
        .map_err(|message| failure(&portable, message))?;
    let library = bridge
        .library(&unit.source, class, &injections, &models)
        .map_err(|message| failure(&portable, message))?;
    let module = bridge.module(class, &portable, &injections, unit.plan.as_ref(), held);
    Ok((library, module))
}

struct DartModels {
    imports: String,
    code: String,
    names: Vec<String>,
}

impl DartModels {
    fn read(snapshot_root: &Path) -> Result<Self, String> {
        let sources = crate::model_sources::ModelSources::read(snapshot_root, "client", "dart")
            .map_err(|failure| failure.to_string())?;
        let mut imports = String::new();
        for (relative, _) in sources.separate_files() {
            let _ = writeln!(
                imports,
                "import '{}';",
                relative.to_string_lossy().replace('\\', "/")
            );
        }
        let code = crate::route_types::Converters::tac_text("dart", snapshot_root)?;
        let mut table =
            crate::route_types::ModelTable::read_realm(snapshot_root, "client", "dart")?;
        table.add_web_events();
        let names = table.record_names();
        Ok(Self {
            imports,
            code,
            names,
        })
    }
}

pub(crate) struct Unit {
    pub(crate) source: String,
    plan: Option<serde_json::Value>,
    clients: Vec<(String, EventStream)>,
}

pub(crate) fn prepare(
    snapshot_root: &Path,
    relative: &Path,
    source: &str,
) -> Result<Unit, Failure> {
    let portable = relative.to_string_lossy().replace('\\', "/");
    crate::behavior::ServiceRoles::read(relative, source)?;
    crate::behavior::StoredState::refuse_sigils(relative, source)?;
    let assembled = crate::annotation_modules::assemble(snapshot_root, relative, source, "tac")?
        .unwrap_or_else(|| source.to_owned());
    let mut events = crate::events::extract(relative, &assembled, "tac")?;
    if let Some(module) = events.as_mut() {
        crate::events::describe(module, relative, snapshot_root, "client")?;
    }
    let class = relative
        .file_stem()
        .and_then(|stem| stem.to_str())
        .unwrap_or_default();
    let plan = match &events {
        Some(events) => event_plan(events, class, &portable)?,
        None => None,
    };
    let clients = events
        .as_ref()
        .map(|events| Unit::client_streams(events, class))
        .unwrap_or_default();
    let events_source = match &events {
        Some(events) => events.source.as_str(),
        None => assembled.as_str(),
    };
    let rewritten = crate::behavior::HttpClientSource::rewrite(relative, events_source)?;
    let events_source = crate::behavior::ServiceRoles::without_roles(
        relative,
        rewritten.as_deref().unwrap_or(events_source),
    )?;
    let lowered = crate::model_sources::ModelSources::client_metadata(snapshot_root, "dart")?
        .lowered(relative, &events_source, |text| {
            crate::behavior::lower(relative, text, "tac")
        })?
        .unwrap_or(events_source);
    Ok(Unit {
        source: lowered,
        plan,
        clients,
    })
}

impl Unit {
    fn client_streams(events: &EventModule, class: &str) -> Vec<(String, EventStream)> {
        events
            .types
            .iter()
            .filter(|event_type| event_type.name != class)
            .flat_map(|event_type| {
                event_type
                    .streams
                    .iter()
                    .filter(|stream| !stream.topic)
                    .map(|stream| (event_type.name.clone(), stream.clone()))
            })
            .collect()
    }
}

fn event_plan(
    events: &EventModule,
    class: &str,
    portable: &str,
) -> Result<Option<serde_json::Value>, Failure> {
    for event_type in &events.types {
        for resource in &event_type.resources {
            if resource.name != "applicationEventPublisher" {
                return Err(failure(
                    portable,
                    format!(
                        "Dart services receive only the applicationEventPublisher resource; '{}' names '{}'.",
                        resource.field, resource.name
                    ),
                ));
            }
        }
    }
    let Some(event_type) = events
        .types
        .iter()
        .find(|event_type| event_type.name == class)
    else {
        return Ok(None);
    };
    let mut event_type = event_type.clone();
    event_type.resources.clear();
    Ok(Some(serde_json::to_value(event_type).unwrap_or_default()))
}

fn failure(portable: &str, detail: impl std::fmt::Display) -> Failure {
    Failure::one(diagnostic(
        1009,
        format!("Cannot compile Dart service '{portable}': {detail}"),
        Some(String::from(
            "Tachyon compiles a Dart service with `dart compile wasm` from the Dart SDK 3.13 or newer on PATH; \
             see docs/adr/0033-dart-browser-services.md.",
        )),
        None,
    ))
}

#[derive(Clone, Debug, PartialEq, Eq)]
struct Field {
    name: String,
    type_name: Option<String>,
    writable: bool,
}

#[derive(Clone, Debug, PartialEq, Eq)]
struct Method {
    name: String,
    parameters: Vec<Parameter>,
    returns: Option<String>,
}

#[derive(Clone, Debug, PartialEq, Eq)]
struct Parameter {
    type_name: Option<String>,
    kind: ParameterKind,
}

#[derive(Clone, Debug, PartialEq, Eq)]
enum ParameterKind {
    Required,
    Optional(Option<String>),
    Named {
        name: String,
        default: Option<String>,
    },
}

#[derive(Clone, Copy)]
enum ParameterGroup {
    Required,
    Optional,
    Named,
}

fn parameters(text: &str, models: &[String]) -> Option<Vec<Parameter>> {
    let mut result = Vec::new();
    for piece in split_top(text, ',') {
        let piece = piece.trim();
        if piece.is_empty() {
            continue;
        }
        let (group, entries) = if let Some(inner) = piece.strip_prefix('[') {
            (
                ParameterGroup::Optional,
                split_top(inner.strip_suffix(']')?, ','),
            )
        } else if let Some(inner) = piece.strip_prefix('{') {
            (
                ParameterGroup::Named,
                split_top(inner.strip_suffix('}')?, ','),
            )
        } else {
            (ParameterGroup::Required, vec![piece])
        };
        for entry in entries {
            let entry = entry.trim();
            if entry.is_empty() {
                continue;
            }
            result.push(parameter(entry, group, models)?);
        }
    }
    Some(result)
}

fn parameter(entry: &str, group: ParameterGroup, models: &[String]) -> Option<Parameter> {
    let parts = split_top(entry, '=');
    let (first, rest) = parts.split_first()?;
    let declaration = first.trim();
    let default = if rest.is_empty() {
        None
    } else {
        Some(rest.join("=").trim().to_owned())
    };
    let mut words = Vec::new();
    for word in declaration.split_whitespace() {
        if !matches!(word, "final" | "covariant" | "required") {
            words.push(word);
        }
    }
    let (name, type_words) = words.split_last()?;
    let type_name = if type_words.is_empty() {
        None
    } else {
        Some(type_words.join(" "))
    };
    if type_name
        .as_deref()
        .is_some_and(|type_name| !json_type(type_name) && !is_model_result(type_name, models))
        || name.starts_with("this.")
    {
        return None;
    }
    let kind = match group {
        ParameterGroup::Required => ParameterKind::Required,
        ParameterGroup::Optional => ParameterKind::Optional(default),
        ParameterGroup::Named => ParameterKind::Named {
            name: (*name).to_owned(),
            default,
        },
    };
    Some(Parameter { type_name, kind })
}

impl Method {
    fn arguments(&self, models: &[String]) -> (String, usize, usize) {
        let mut positional = 0;
        let mut required = 0;
        for parameter in &self.parameters {
            if !matches!(parameter.kind, ParameterKind::Named { .. }) {
                positional += 1;
            }
            if parameter.kind == ParameterKind::Required {
                required += 1;
            }
        }
        let named = positional < self.parameters.len();
        let mut arguments = Vec::new();
        for (index, parameter) in self.parameters.iter().enumerate() {
            arguments.push(Self::argument(parameter, index, positional, models));
        }
        (
            arguments.join(", "),
            required,
            positional + usize::from(named),
        )
    }

    fn argument(
        parameter: &Parameter,
        index: usize,
        positional: usize,
        models: &[String],
    ) -> String {
        let type_name = parameter.type_name.as_deref();
        let value = format!("values[{index}]");
        if let Some(shape) = DartModelShape::of(type_name, models) {
            return crate::route_types::DartValues::read(&shape, &value);
        }
        match &parameter.kind {
            ParameterKind::Required => convert(type_name, &value),
            ParameterKind::Optional(default) => format!(
                "values.length > {index} ? {} : {}",
                convert(type_name, &value),
                default.as_deref().unwrap_or("null")
            ),
            ParameterKind::Named { name, default } => {
                let option = format!("__TacDartBridge.option(values, {positional}, r'{name}')");
                format!(
                    "{name}: __TacDartBridge.named(values, {positional}, r'{name}') ? {} : {}",
                    convert(type_name, &option),
                    default.as_deref().unwrap_or("null")
                )
            }
        }
    }
}

